-- ---------------------------------------------------------------------------
-- Helpers de autorización. Se mantienen fuera del esquema público.
-- ---------------------------------------------------------------------------

create or replace function private.app_user_id()
returns bigint
language sql
stable
security definer
set search_path = ''
as $$
  select u.id
  from public.usuarios u
  where u.auth_user_id = (select auth.uid())
    and u.activo = true
  limit 1
$$;

create or replace function private.app_is_admin()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists(
    select 1
    from public.usuarios u
    where u.auth_user_id = (select auth.uid())
      and u.activo = true
      and u.es_admin = true
  )
$$;

create or replace function private.app_has_permission(p_permiso text)
returns boolean
language plpgsql
stable
security definer
set search_path = ''
as $$
declare
  v_permisos jsonb;
begin
  if (select private.app_is_admin()) then
    return true;
  end if;

  select
    case
      when trim(coalesce(u.permisos,'')) like '[%'
        then trim(u.permisos)::jsonb
      else '[]'::jsonb
    end
  into v_permisos
  from public.usuarios u
  where u.auth_user_id = (select auth.uid())
    and u.activo = true
  limit 1;

  return coalesce((v_permisos ->> p_permiso)::boolean, false)
      or (p_permiso = 'agregar_tasa' and coalesce((v_permisos ->> 'parametros')::boolean, false));
exception when others then
  return false;
end;
$$;

revoke all on function private.app_user_id() from public;
revoke all on function private.app_is_admin() from public;
revoke all on function private.app_has_permission(text) from public;
grant usage on schema private to authenticated;
grant execute on function private.app_user_id() to authenticated;
grant execute on function private.app_is_admin() to authenticated;
grant execute on function private.app_has_permission(text) to authenticated;

