-- El precio objetivo solo puede ser modificado por administrador, igual que en
-- la versión Flask. El resto de campos del producto conserva su permiso normal.
create or replace function private.enforce_producto_price_admin()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  if tg_op = 'UPDATE'
     and coalesce(new.precio_usd,0) is distinct from coalesce(old.precio_usd,0)
     and not (select private.app_is_admin()) then
    raise exception 'No es posible realizar esta operación.';
  end if;
  return new;
end;
$$;

drop trigger if exists trg_productos_precio_admin on public.productos;
create trigger trg_productos_precio_admin
before update on public.productos
for each row execute function private.enforce_producto_price_admin();

revoke all on function private.enforce_producto_price_admin() from public, anon, authenticated;

